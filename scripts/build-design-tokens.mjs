import fs from 'node:fs/promises';
const definition = JSON.parse(await fs.readFile(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const css = `/* Generated from design/tokens.json. Run npm run design:tokens; do not edit this file. */\n:root {\n${Object.entries(definition.tokens).map(([key, value]) => `  --${key}: ${value};`).join('\n')}\n}\n`;
await fs.writeFile(new URL('../public/design-tokens.css', import.meta.url), css);
await fs.writeFile(new URL('../public/design-tokens.json', import.meta.url), JSON.stringify(definition, null, 2) + '\n');
console.log(`Generated ${Object.keys(definition.tokens).length} design tokens.`);
